func ValidateAccessPermissions(app string, values []string) ([]string, error) {
	catalog, ok := AccessCatalog()[app]
	if !ok {
		return nil, fmt.Errorf("unknown application")
	}
	allowed := map[string]bool{}
	for _, p := range catalog {
		allowed[p.Code] = true
	}
	seen := map[string]bool{}
	result := []string{}
	for _, code := range values {
		if !allowed[code] {
			return nil, fmt.Errorf("unknown or non-delegatable permission: %s", code)
		}
		if !AccessPermissionAvailable(app, code) {
			return nil, ErrAccessPermissionUnavailable
		}
		if !seen[code] {
			result = append(result, code)
			seen[code] = true
		}
	}
	if app == "sd" {
		for _, code := range append([]string(nil), result...) {
			if strings.HasSuffix(code, ":read_all") {
				read := strings.TrimSuffix(code, "_all")
				if allowed[read] && !seen[read] {
					result = append(result, read)
					seen[read] = true
				}
			}
		}
	}
	if err := validateAccessDependencies(app, seen); err != nil {
		return nil, err
	}
	sort.Strings(result)
	return result, nil
}
func AccessPositionKey(name string) string { return strings.ToLower(strings.TrimSpace(name)) }

// SenimDesk client-company contracts allow fewer actions than a service staff tenant.
func SDClientPermissions(items []AccessPermission) []AccessPermission {
	actions := map[string]string{"projects": "read,read_all", "objects": "create,read,update,delete,export", "inventory": "create,read,update,delete,export", "tickets": "read,read_all,create,update,delete,export", "knowledge": "create,read,update,delete,export", "reports": "read,export", "workers": "create,read,update,delete,export", "groups": "create,read,update,delete,export", "clients": "read,read_all,create,update,delete"}
	out := []AccessPermission{}
	for _, p := range items {
		r, a, ok := strings.Cut(p.Code, ":")
		if ok && strings.Contains(","+actions[r]+",", ","+a+",") {
			out = append(out, p)
		}
	}
	return out
}
