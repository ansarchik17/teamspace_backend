package repository

import (
	"encoding/json"
	"os"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
	"github.com/west6ide/workspace-backend/internal/domain"
	"go.uber.org/zap"
)

func TestAdministrationOverviewIsolationAndCapabilities(t *testing.T) {
	ctx, db, a, b := newAdministrationStorageTestDB(t)
	for _, file := range []string{"20261012000200_company_user_blocks.sql", "20261012000300_company_modules.sql", "20260914000000_create_organization_identity_providers.sql"} {
		data, err := os.ReadFile("../../db/migrations/" + file)
		require.NoError(t, err)
		_, err = db.Exec(ctx, strings.Split(string(data), "-- +goose Down")[0])
		require.NoError(t, err, file)
	}
	_, err := db.Exec(ctx, `CREATE TABLE teams(organization_id UUID,deleted_at TIMESTAMPTZ)`)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `INSERT INTO teams(organization_id) VALUES($1),($2),($2)`, a, b)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `INSERT INTO organization_identity_providers(organization_id,provider_type,alias,display_name,enabled,status,last_error,settings) VALUES($1,'oidc','own','Own',true,'active','private-technical-error','{"clientSecret":"private-secret"}'),($2,'saml','foreign','Foreign',false,'error','foreign-private','{}')`, a, b)
	require.NoError(t, err)
	r := NewOrganizationRepository(db, zap.NewNop())
	r.SetStorageCapacityProvider(testStorageCapacity{})
	own, err := r.AdministrationOverview(ctx, 2, nil)
	require.NoError(t, err)
	require.Equal(t, a, own.Organization.ID)
	require.Equal(t, int64(2), own.Users.Total)
	require.Equal(t, int64(1), own.UnitCount)
	require.Len(t, own.Modules, 5)
	require.Equal(t, int64(1), own.Integrations.Total)
	require.Equal(t, int64(1), own.Integrations.Enabled)
	require.False(t, own.Capabilities.SetUserQuotas)
	require.False(t, own.Capabilities.SetCompanyQuota)
	require.False(t, own.Capabilities.ManageIdentityProviders)
	platformCompany, err := r.AdministrationOverview(ctx, 1, &a)
	require.NoError(t, err)
	require.True(t, platformCompany.Capabilities.ManageIdentityProviders)
	payload, err := json.Marshal(own)
	require.NoError(t, err)
	require.NotContains(t, string(payload), "private")
	require.NotContains(t, string(payload), "Foreign")
	_, err = r.AdministrationOverview(ctx, 3, nil)
	require.Error(t, err)
	_, err = r.AdministrationOverview(ctx, 2, &b)
	require.Error(t, err)
	_, err = r.PlatformAdministrationOverview(ctx, 2)
	require.Error(t, err)
	global, err := r.PlatformAdministrationOverview(ctx, 1)
	require.NoError(t, err)
	require.Equal(t, int64(2), global.Companies.Total)
	require.Equal(t, int64(4), global.Users.Total)
	require.Equal(t, int64(3), global.UnitCount)
	require.Equal(t, int64(2), global.Integrations.Total)
	quota, revision := int64(250), int64(0)
	require.NoError(t, r.SetAdministrationStorage(ctx, 1, &a, domain.AdministrationStorageRequest{QuotaBytes: &quota, Revision: &revision}))
	own, err = r.AdministrationOverview(ctx, 2, nil)
	require.NoError(t, err)
	require.True(t, own.Capabilities.SetUserQuotas)
	require.Len(t, own.RecentAudit.Items, 1)

	_, err = db.Exec(ctx, `INSERT INTO organization_admin_audit(organization_id,actor_id,action,object_type,object_id,before_value,after_value) SELECT $1::uuid,1,'test','organization',($1::uuid)::text,'{}'::jsonb,'{}'::jsonb FROM generate_series(1,6)`, a)
	require.NoError(t, err)
	own, err = r.AdministrationOverview(ctx, 2, nil)
	require.NoError(t, err)
	require.Len(t, own.RecentAudit.Items, 5)
	require.NotNil(t, own.RecentAudit.NextBeforeID)
	_, err = db.Exec(ctx, `INSERT INTO organization_user_blocks(user_id,organization_id,actor_id) VALUES(3,$1,1)`, a)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `UPDATE users SET is_active=false WHERE id=3`)
	require.NoError(t, err)
	own, err = r.AdministrationOverview(ctx, 2, nil)
	require.NoError(t, err)
	require.Equal(t, int64(1), own.Users.Blocked)
	require.Equal(t, int64(1), own.Users.Inactive)
	_, err = db.Exec(ctx, `UPDATE organizations SET status='suspended' WHERE id=$1`, a)
	require.NoError(t, err)
	_, err = r.AdministrationOverview(ctx, 2, nil)
	require.ErrorIs(t, err, domain.ErrOrganizationNotFound)
	own, err = r.AdministrationOverview(ctx, 1, &a)
	require.NoError(t, err)
	require.False(t, own.Capabilities.ManageUsers)
	require.False(t, own.Capabilities.SetUserQuotas)
	require.True(t, own.Capabilities.ManageCompanyLifecycle)
	require.True(t, own.Capabilities.AssignOwner)
	_, err = db.Exec(ctx, `UPDATE users SET is_active=false WHERE id=1`)
	require.NoError(t, err)
	_, err = r.PlatformAdministrationOverview(ctx, 1)
	require.Error(t, err)
}
