package server

import (
	"github.com/gin-gonic/gin"
	"github.com/west6ide/workspace-backend/internal/handler"
)

func registerDriveRoutes(protected *gin.RouterGroup, drive *handler.DriveHandler) {
	docs := protected.Group("/docs")
	docs.POST("/files", drive.CreateDocument)
	docs.POST("/import", drive.ImportDocument)
	docs.GET("/files/:id/export", drive.ExportDocument)
	docs.GET("/files/:id/save-state", drive.OfficeSaveState)
	docs.POST("/files/:id/recover", drive.RecoverOfficeSession)
	docs.GET("/files/:id/participants", drive.OfficeParticipants)
	docs.GET("/templates", drive.ListDocumentTemplates)
	docs.POST("/templates", drive.PublishDocumentTemplate)
	docs.DELETE("/templates/:id", drive.DeleteDocumentTemplate)

	grp := protected.Group("/drive")

	grp.POST("/folders", drive.CreateFolder)
	grp.GET("/folders/:id", drive.GetFolder)
	grp.GET("/folders/:id/children", drive.ListFolderChildren)
	grp.GET("/folders/:id/access-report", drive.ExportFolderAccessReport)
	grp.PUT("/folders/:id", drive.UpdateFolder)
	grp.DELETE("/folders/:id", drive.DeleteFolder)
	grp.GET("/files/download", drive.DownloadFile)

	grp.POST("/files", drive.UploadFile)
	grp.GET("/files/:id", drive.GetFile)
	grp.GET("/files/:id/versions", drive.ListFileVersions)
	grp.POST("/files/:id/versions", drive.UploadFileVersion)
	grp.GET("/files/:id/versions/:version/download", drive.DownloadFileVersion)
	grp.HEAD("/files/:id/versions/:version/download", drive.DownloadFileVersion)
	grp.POST("/files/:id/versions/:version/restore", drive.RestoreFileVersion)
	grp.GET("/files/:id/preview", drive.GetFilePreview)
	grp.GET("/files/:id/preview/content", drive.PreviewFileContent)
	grp.HEAD("/files/:id/preview/content", drive.PreviewFileContent)
	grp.GET("/files/:id/preview/office", drive.PreviewOfficeFile)
	grp.GET("/files/:id/download", drive.DownloadFile)
	grp.PUT("/files/:id", drive.UpdateFile)
	grp.DELETE("/files/:id", drive.DeleteFile)
	grp.POST("/delete-requests/:id/approve", drive.ApproveDeleteRequest)
	grp.POST("/delete-requests/:id/reject", drive.RejectDeleteRequest)

	grp.POST("/permissions", drive.GrantPermission)
	grp.PUT("/permissions", drive.UpdatePermission)
	grp.DELETE("/permissions", drive.RevokePermission)
	grp.POST("/ownership/transfer", drive.TransferOwnership)
	grp.GET("/permissions/users-with-access", drive.GetUsersWithAccess)
	grp.GET("/permissions/users-without-access", drive.GetUsersWithoutAccess)
	grp.GET("/permissions/my", drive.GetMyPermission)

	grp.GET("/items", drive.ListAllDrive)
	grp.GET("/files/:id/tags", drive.GetFileTags)
	grp.PUT("/files/:id/tags", drive.SetFileTags)
	grp.GET("/activity", drive.ListActivity)
	grp.GET("/items/own", drive.ListOwnDrive)
	grp.GET("/items/shared", drive.ListSharedDrive)
	grp.GET("/shared/users", drive.ListSharingUsers)
	grp.GET("/search", drive.SearchItems)
	grp.POST("/search/query", drive.SearchContent)
	grp.GET("/file-types", drive.GetFileTypes)
	grp.GET("/storage", drive.GetDriveStorage)
	grp.GET("/summary", drive.GetWorkspaceSummary)
	grp.GET("/favorites", drive.ListFavorites)
	grp.POST("/favorites", drive.AddFavorite)
	grp.DELETE("/favorites/:type/:id", drive.RemoveFavorite)
	grp.GET("/trash", drive.ListTrash)
	grp.POST("/trash/:type/:id/restore", drive.RestoreTrashItem)
	grp.GET("/onlyoffice/editor-link", drive.OnlyOfficeEditorLink)
	grp.GET("/collabora/editor", drive.CollaboraEditorPage)
	grp.POST("/items/batch", drive.BatchItems)
	grp.POST("/items/copy", drive.CopyItem)
	grp.POST("/items/move", drive.MoveItem)

	grp.GET("/recent", drive.ListRecent)
	grp.DELETE("/share/link/:token", drive.RevokePublicLink)
	grp.POST("/share/link", drive.CreatePublicLink)
	grp.GET("/share/link", drive.ListPublicLinks)
	grp.POST("/share/link/:token/accept", drive.AcceptPublicLink)

}
