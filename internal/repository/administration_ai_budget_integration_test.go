package repository

import (
	"os"
	"strings"
	"testing"
	"time"

	"github.com/google/uuid"
	"github.com/stretchr/testify/require"
	"go.uber.org/zap"
)

func TestAdministrationAIBudget(t *testing.T) {
	ctx, db, a, b := newAdministrationStorageTestDB(t)
	for _, file := range []string{"20261020100100_ai_budget_settings.sql", "20261020100200_ai_accounting_periods.sql", "20261020100300_ai_operations_and_reservations.sql", "20261022100100_ai_five_hour_request_windows.sql", "20261022100200_ai_personal_weekly_windows.sql", "20261020100900_ai_enforcement_mode_unconfigured.sql", "20261022100400_ai_personal_access_policy.sql", "20261022100500_ai_final_request_cutoffs.sql"} {
		data, err := os.ReadFile("../../db/migrations/" + file)
		require.NoError(t, err)
		_, err = db.Exec(ctx, strings.Split(string(data), "-- +goose Down")[0])
		require.NoError(t, err)
	}
	r := NewOrganizationRepository(db, zap.NewNop())
	now := time.Date(2026, 10, 16, 6, 0, 0, 0, time.UTC)
	out, err := r.administrationAIBudgetAt(ctx, 2, nil, now)
	require.NoError(t, err)
	require.False(t, out.Configured)
	require.Nil(t, out.WeeklyBudget)
	require.Nil(t, out.Available)
	require.Nil(t, out.Window)
	require.Zero(t, out.Committed)
	require.True(t, out.CanSetUserQuotas)
	require.False(t, out.CanSetCompanyBudget)
	empty := uuid.New()
	_, err = db.Exec(ctx, `INSERT INTO organizations(id,name,slug) VALUES($1,'Empty','empty-ai-budget')`, empty)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `INSERT INTO organization_ai_budgets(organization_id,weekly_budget_microcredits,max_five_hour_microcredits) VALUES($1,1000,100)`, empty)
	require.NoError(t, err)
	emptySummary, err := r.administrationAIBudgetAt(ctx, 1, &empty, now)
	require.NoError(t, err)
	require.Zero(t, emptySummary.Allocated)
	require.Zero(t, emptySummary.Used)
	require.Equal(t, int64(1000), *emptySummary.Available)
	require.Equal(t, int64(1000), *emptySummary.Unallocated)
	_, err = r.administrationAIBudgetAt(ctx, 3, nil, now)
	require.Error(t, err, "ordinary employee")
	_, err = r.administrationAIBudgetAt(ctx, 2, &b, now)
	require.Error(t, err, "director cannot use platform scope")
	_, err = db.Exec(ctx, `INSERT INTO organization_ai_budgets(organization_id,weekly_budget_microcredits,max_five_hour_microcredits,service_weekly_quota_microcredits) VALUES($1,1000,100,100)`, a)
	require.NoError(t, err)
	out, err = r.administrationAIBudgetAt(ctx, 1, &a, now)
	require.NoError(t, err)
	require.True(t, out.Configured)
	require.Equal(t, int64(1000), *out.Available)
	require.Equal(t, int64(0), out.Allocated)
	require.Equal(t, int64(1000), *out.Unallocated)
	require.Equal(t, 100, *out.RemainingPercent)
	require.Nil(t, out.Window)
	require.True(t, out.CanSetCompanyBudget)
	require.False(t, out.CanSetServiceQuota)
	_, err = db.Exec(ctx, `INSERT INTO organization_ai_user_quotas(organization_id,user_id,weekly_quota_microcredits,five_hour_limit_microcredits) VALUES($1,2,200,100),($1,3,600,100)`, a)
	require.NoError(t, err)
	anchor := now.Add(-7 * 24 * time.Hour)
	_, err = db.Exec(ctx, `INSERT INTO organization_ai_weekly_anchors VALUES($1,$2)`, a, anchor)
	require.NoError(t, err)
	current, old, five := uuid.New(), uuid.New(), uuid.New()
	_, err = db.Exec(ctx, `INSERT INTO organization_ai_weekly_periods(id,organization_id,anchor_at,starts_at,ends_at,used_microcredits) VALUES($1,$2,$3,$4,$5,150),($6,$2,$3,$3,$4,0)`, current, a, anchor, now, now.Add(168*time.Hour), old)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `INSERT INTO user_ai_five_hour_anchors VALUES(3,$1)`, now)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `INSERT INTO user_ai_five_hour_periods(id,user_id,anchor_at,starts_at,ends_at) VALUES($1,3,$2,$2,$3)`, five, now, now.Add(5*time.Hour))
	require.NoError(t, err)
	_, err = db.Exec(ctx, `INSERT INTO organization_ai_user_weekly_usage(organization_id,period_id,user_id,used_microcredits) VALUES($1,$2,3,100)`, a, current)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `INSERT INTO organization_ai_service_weekly_usage(organization_id,period_id,used_microcredits) VALUES($1,$2,50)`, a, current)
	require.NoError(t, err)
	reserve := func(period uuid.UUID, kind string, amount int64) uuid.UUID {
		t.Helper()
		op, attempt, id := uuid.New(), uuid.New(), uuid.New()
		_, err := db.Exec(ctx, `INSERT INTO ai_usage_operations(id,organization_id,user_id,payer_kind,operation_kind,idempotency_key,request_fingerprint) VALUES($1,$2,3,$3,'test',$4,decode(repeat('ab',32),'hex'))`, op, a, kind, op.String())
		require.NoError(t, err)
		var personal *uuid.UUID
		if kind == "user" {
			personal = &five
		}
		_, err = db.Exec(ctx, `INSERT INTO ai_usage_attempts(id,operation_id,organization_id,attempt_number,provider_id,endpoint_kind,requested_model,credit_policy_version,usage_adapter_version,input_weight_microcredits,company_period_id,five_hour_period_id) VALUES($1,$2,$3,1,'nitec','chat','model','credits-v1','test',1000,$4,$5)`, attempt, op, a, period, personal)
		require.NoError(t, err)
		_, err = db.Exec(ctx, `INSERT INTO ai_usage_reservations(id,attempt_id,reserved_microcredits) VALUES($1,$2,$3)`, id, attempt, amount)
		require.NoError(t, err)
		return id
	}
	reserve(current, "user", 100)
	reserve(old, "user", 80)
	released := reserve(current, "user", 40)
	reserve(current, "service", 20)
	_, err = db.Exec(ctx, `UPDATE ai_usage_reservations SET status='released',closed_at=now() WHERE id=$1`, released)
	require.NoError(t, err)
	_, err = db.Exec(ctx, `UPDATE users SET is_active=false WHERE id=3`)
	require.NoError(t, err)
	out, err = r.administrationAIBudgetAt(ctx, 2, nil, now)
	require.NoError(t, err)
	require.Equal(t, int64(800), out.EmployeeAllocated)
	require.Equal(t, int64(800), out.Allocated)
	require.Equal(t, int64(870), out.Committed)
	require.Equal(t, int64(150), out.Used)
	require.Equal(t, int64(200), out.Reserved)
	require.Equal(t, int64(80), out.CarriedReserved)
	require.Equal(t, int64(650), *out.Available)
	require.Equal(t, int64(130), *out.Unallocated)
	require.Equal(t, 65, *out.RemainingPercent)
	require.Equal(t, int64(650), out.Service.Available)
	// The next idle week has no persisted row, but unresolved old holds remain.
	out, err = r.administrationAIBudgetAt(ctx, 2, nil, now.Add(168*time.Hour))
	require.NoError(t, err)
	require.Nil(t, out.PeriodID)
	require.NotNil(t, out.Window)
	require.Equal(t, int64(0), out.Used)
	require.Equal(t, int64(200), out.CarriedReserved)
	require.Equal(t, int64(800), *out.Available)
	var count int
	require.NoError(t, db.QueryRow(ctx, `SELECT count(*) FROM organization_ai_weekly_periods`).Scan(&count))
	require.Equal(t, 2, count, "read must not create idle period")
	// Lower personal settings below confirmed usage: obligations do not vanish.
	_, err = db.Exec(ctx, `UPDATE organization_ai_user_quotas SET weekly_quota_microcredits=0 WHERE organization_id=$1 AND user_id=3`, a)
	require.NoError(t, err)
	out, err = r.administrationAIBudgetAt(ctx, 2, nil, now)
	require.NoError(t, err)
	require.Equal(t, int64(550), out.Committed)
	_, err = db.Exec(ctx, `UPDATE users SET organization_id=$1 WHERE id=3`, b)
	require.NoError(t, err)
	former, err := r.administrationAIBudgetAt(ctx, 2, nil, now)
	require.NoError(t, err)
	require.Equal(t, int64(550), former.Committed, "former employee's usage and holds still commit company budget")
	require.Equal(t, int64(200), former.EmployeeAllocated)
	_, err = db.Exec(ctx, `UPDATE organization_ai_budgets SET weekly_budget_microcredits=0 WHERE organization_id=$1`, a)
	require.NoError(t, err)
	out, err = r.administrationAIBudgetAt(ctx, 2, nil, now)
	require.NoError(t, err)
	require.Zero(t, *out.Available)
	require.Equal(t, int64(550), *out.Overcommitted)
	require.Nil(t, out.RemainingPercent)
	_, err = db.Exec(ctx, `UPDATE organizations SET status='suspended' WHERE id=$1`, a)
	require.NoError(t, err)
	_, err = r.administrationAIBudgetAt(ctx, 2, nil, now)
	require.Error(t, err)
	platform, err := r.administrationAIBudgetAt(ctx, 1, &a, now)
	require.NoError(t, err)
	require.True(t, platform.CanSetCompanyBudget)
	require.False(t, platform.CanSetUserQuotas)
}
